#!/usr/bin/env python3
"""Score our detections against the published ground truth; the only reader of the labels.

Usage (DATABASE_URL, SLM_SCHEMA, SLM_DATA_DIR from the environment):
    uv run python scripts/ground_truth.py openstack [--output docs/results/ground-truth.md]

`openstack` (T11): reads the OpenStack labels, raw/anomaly_labels.txt under SLM_DATA_DIR (the four
instances with injected faults), calls `latency_stats` exactly as an agent would (metric 'spawn'
and 'build', group_by 'instance'), and reports how many labelled instances timing flags at several
min_z thresholds, where each ranks, which flagged instance is not labelled (a Hypothesis), whether
any Log Entry of a labelled instance is above INFO (so text search could find it), and how long the
derive step and the calls take.

The result goes into its own section of docs/results/ground-truth.md, between
`<!-- BEGIN openstack -->` and `<!-- END openstack -->`; other sections of the file (T10's BGL
result) are left as they are.

No tool, derive step or canonical table may read the labels (plan section 2.2); tests enforce it.
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import anyio
import psycopg
from mcp import Client
from mcp_types import CallToolResult, TextContent
from psycopg import sql

import derive
from serenedb_log_mcp.config import ConfigError, Settings, load_settings, set_settings
from serenedb_log_mcp.corpus.datasets import relation
from serenedb_log_mcp.server import create_server

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "docs" / "results" / "ground-truth.md"
LABELS = Path("raw") / "anomaly_labels.txt"
INSTANCE_STEP = ROOT / "sql" / "derive" / "60_os_instance.sql"
INSTANCE_HEADER = "CREATE OR REPLACE TABLE ${slm}.os_instance AS"
THRESHOLDS = (3.5, 5.0, 8.0)
DEFAULT_MIN_Z = 5.0
METRICS = ("spawn", "build")
ROWS = 50
TOP = 6
UUID_RE = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
TITLE = (
    "# Ground truth\n\n"
    "Our detections scored against the published labels, generated by `scripts/ground_truth.py`.\n"
)


class GroundTruthError(Exception):
    """A problem the user can fix; printed without a traceback."""


# ----------------------------------------------------------------- pure parts


def parse_labels(text: str) -> list[str]:
    """The instance UUIDs of the label file, in order, without repeats."""
    found = list(dict.fromkeys(UUID_RE.findall(text.lower())))
    if not found:
        raise GroundTruthError("the label file holds no instance ids")
    return found


@dataclass(frozen=True)
class Ranked:
    """One instance as latency_stats ranked it: its id and whether the tool flagged it."""

    instance_id: str
    flagged: bool


@dataclass(frozen=True)
class Score:
    min_z: float
    flagged: int
    true_positives: int
    labels: int
    label_ranks: dict[str, int | None]
    unlabelled_flagged: list[str]

    @property
    def recall(self) -> tuple[int, int]:
        return self.true_positives, self.labels

    @property
    def precision(self) -> tuple[int, int]:
        return self.true_positives, self.flagged


def score(ranked: Sequence[Ranked], labels: set[str], min_z: float) -> Score:
    """How the ranking does against the labels; `ranked` carries the tool's flags at `min_z`."""
    flagged = [row.instance_id for row in ranked if row.flagged]
    ranks = {row.instance_id: position for position, row in enumerate(ranked, start=1)}
    return Score(
        min_z=min_z,
        flagged=len(flagged),
        true_positives=sum(instance in labels for instance in flagged),
        labels=len(labels),
        label_ranks={label: ranks.get(label) for label in sorted(labels, key=lambda x: ranks.get(x, 10**9))},
        unlabelled_flagged=[instance for instance in flagged if instance not in labels],
    )


def replace_section(document: str, name: str, body: str) -> str:
    """`document` with the block between the BEGIN and END markers of `name` set to `body`."""
    begin, end = f"<!-- BEGIN {name} -->", f"<!-- END {name} -->"
    block = f"{begin}\n{body.strip()}\n{end}"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.DOTALL)
    if pattern.search(document):
        return pattern.sub(lambda _: block, document, count=1)
    return document.rstrip() + "\n\n" + block + "\n"


# ----------------------------------------------------------------- measuring


def call_latency_stats(**arguments: Any) -> dict[str, Any]:
    """latency_stats through an in-process MCP client, as an agent calls it."""

    async def one_call() -> CallToolResult:
        async with Client(create_server(), mode="legacy") as client:
            result = await client.call_tool("latency_stats", arguments)
            assert isinstance(result, CallToolResult)
            return result

    result = anyio.run(one_call)
    if result.is_error or result.structured_content is None:
        first = result.content[0] if result.content else None
        text = first.text if isinstance(first, TextContent) else "(no text)"
        raise GroundTruthError(f"latency_stats failed: {text}")
    return dict(result.structured_content)


@dataclass(frozen=True)
class MetricResult:
    metric: str
    rows: list[dict[str, Any]]
    summary: dict[str, Any]
    query_ms: float
    scores: list[Score]


def measure_metric(metric: str, labels: set[str]) -> MetricResult:
    """One latency_stats call per threshold; the flags are the tool's own (z >= min_z, unrounded)."""
    scores: list[Score] = []
    default: dict[str, Any] = {}
    for threshold in THRESHOLDS:
        evidence = call_latency_stats(
            role="engineer", metric=metric, group_by="instance", min_z=threshold, limit=ROWS
        )
        rows = [dict(zip(evidence["columns"], row, strict=True)) for row in evidence["rows"]]
        ranked = [Ranked(str(row["instance_id"]), bool(row["flagged"])) for row in rows]
        if sum(r.flagged for r in ranked) != evidence["summary"]["flagged_total"]:
            raise GroundTruthError(
                f"latency_stats flags {evidence['summary']['flagged_total']} instances at min_z "
                f"{threshold:g}, more than the {len(rows)} rows returned; the scores need more rows"
            )
        scores.append(score(ranked, labels, threshold))
        if threshold == DEFAULT_MIN_Z:
            default = {"rows": rows, "summary": evidence["summary"], "query_ms": evidence["query_ms"]}
    return MetricResult(
        metric=metric,
        rows=list(default["rows"]),
        summary=dict(default["summary"]),
        query_ms=float(default["query_ms"]),
        scores=scores,
    )


def label_entries(conn: psycopg.Connection[Any], labels: Sequence[str]) -> list[tuple[str, int, int]]:
    """Per labelled instance: its Log Entries and how many are above INFO."""
    statement = sql.SQL(
        "SELECT instance_ref, count(*), count(*) FILTER (WHERE level <> 'INFO') FROM {} "
        "WHERE instance_ref = ANY(%s::VARCHAR[]) GROUP BY 1 ORDER BY 1"
    ).format(relation("openstack").table)
    return [(str(r[0]), int(r[1]), int(r[2])) for r in conn.execute(statement, [list(labels)]).fetchall()]


def derive_seconds(conn: psycopg.Connection[Any], schema: str) -> float:
    """How long the os_instance derive step takes, rebuilt into a temporary table (nothing shared changes)."""
    text = INSTANCE_STEP.read_text()
    if INSTANCE_HEADER not in text:
        raise GroundTruthError(f"{INSTANCE_STEP.name} no longer starts its table with {INSTANCE_HEADER!r}")
    timing = text.replace(INSTANCE_HEADER, "CREATE OR REPLACE TEMPORARY TABLE os_instance_timing AS")
    row = conn.execute("SELECT version()").fetchone()
    version = derive.serenedb_version(str(row[0]) if row else "")
    statements = derive.split_statements(derive.render(timing, derive.variables(schema, "public", version)))
    started = time.perf_counter()
    for statement in statements:
        conn.execute(statement)
    seconds = time.perf_counter() - started
    conn.execute("DROP TABLE IF EXISTS temp.main.os_instance_timing")
    return seconds


# ----------------------------------------------------------------- the report


def _ranks(score: Score) -> str:
    return ", ".join(
        "not in the top 50" if rank is None else str(rank) for rank in score.label_ranks.values()
    )


def render_openstack(
    *,
    labels: Sequence[str],
    results: Sequence[MetricResult],
    entries: Sequence[tuple[str, int, int]],
    derive_s: float,
    schema: str,
    version: str,
    generated: datetime,
) -> str:
    spawn = next(r for r in results if r.metric == "spawn")
    default = next(s for s in spawn.scores if s.min_z == DEFAULT_MIN_Z)
    found, total = default.recall
    label_set = set(labels)
    lines = [
        "## OpenStack: slow spawns found by timing (T11)",
        "",
        f"Generated by `uv run python scripts/ground_truth.py openstack` on {generated:%Y-%m-%d %H:%M} UTC "
        f"against schema `{schema}` ({version}). The labels, `{LABELS.as_posix()}` with {len(labels)} "
        "instances, are read only by this script; the derive step and `latency_stats` never see them.",
        "",
        f"**Result: {found} of {total}.** `latency_stats(metric='spawn', group_by='instance')` flags "
        f"{default.flagged} instances at the default min_z {DEFAULT_MIN_Z:g}; {found} of them are labelled, "
        f"ranked {_ranks(default)} by spawn time. The robust z-score is (spawn_s - median) / (1.4826 * MAD) "
        f"over {spawn.summary['reference_instances']:,} instances (median {spawn.summary['median_s']} s, "
        f"MAD {spawn.summary['mad_s']} s).",
        "",
        "| Metric | min_z | Flagged | Labelled and flagged | Precision | Ranks of the labelled instances |",
        "|---|---|---|---|---|---|",
    ]
    for result in results:
        for s in result.scores:
            marker = " (default)" if s.min_z == DEFAULT_MIN_Z else ""
            lines.append(
                f"| {result.metric} | {s.min_z:g}{marker} | {s.flagged} | {s.true_positives} of {s.labels} | "
                f"{s.true_positives}/{s.flagged} | {_ranks(s)} |"
            )
    lines += [
        "",
        f"The {TOP} slowest spawns:",
        "",
        "| Rank | Instance | Source | spawn_s | spawn_z | image_s | image_z | Spawn Log Entry at "
        "| Flagged | Label |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for position, row in enumerate(spawn.rows[:TOP], start=1):
        labelled = row["instance_id"] in label_set
        verdict = (
            "labelled" if labelled else ("**not labelled: Hypothesis**" if row["flagged"] else "not labelled")
        )
        lines.append(
            f"| {position} | `{row['instance_id']}` | {row['source_id']} | {row['spawn_s']} | "
            f"{row['spawn_z']} | "
            f"{row['image_s']} | {row['image_z']} | {str(row['spawn_ts']).replace('T', ' ')} | "
            f"{'yes' if row['flagged'] else 'no'} | {verdict} |"
        )
    for instance in default.unlabelled_flagged:
        row = next(r for r in spawn.rows if r["instance_id"] == instance)
        lines += [
            "",
            f"**`{instance}` is a Hypothesis.** Timing flags it (spawn_z {row['spawn_z']}, image_z "
            f"{row['image_z']}, source {row['source_id']}, spawn Log Entry at "
            f"{str(row['spawn_ts']).replace('T', ' ')}), but the label file does not list it. It is either "
            f"an injected fault the labels miss or the slowest ordinary spawn; the logs cannot tell which.",
        ]
    above_info = sum(n for _, _, n in entries)
    lines += [
        "",
        f"**Text search finds none of them.** The {len(entries)} labelled instances have "
        f"{', '.join(str(n) for _, n, _ in entries)} Log Entries; {above_info} of them are above INFO, so "
        "no ERROR, WARNING or CRITICAL line points at them. Only their timing does.",
        "",
        f"**Timings.** The os_instance derive step took {derive_s:.2f} s (rebuilt into a temporary table). "
        + ", ".join(f"latency_stats(metric='{r.metric}') took {r.query_ms:.0f} ms" for r in results)
        + " in SereneDB (Evidence query_ms).",
        "",
        "Labelled instances, in label-file order: " + ", ".join(f"`{label}`" for label in labels) + ".",
    ]
    return "\n".join(lines)


def read_labels(settings: Settings) -> list[str]:
    """The labelled OpenStack instances from SLM_DATA_DIR; the one place that opens the label file."""
    label_path = settings.data_dir / LABELS
    if not label_path.is_file():
        raise GroundTruthError(f"{label_path} is missing; run `make fetch-data` or set SLM_DATA_DIR")
    return parse_labels(label_path.read_text())


def run_openstack(output: Path) -> str:
    settings = load_settings()
    set_settings(settings)
    labels = read_labels(settings)
    results = [measure_metric(metric, set(labels)) for metric in METRICS]
    with psycopg.connect(settings.database_url, autocommit=True) as conn:
        entries = label_entries(conn, labels)
        seconds = derive_seconds(conn, settings.slm_schema)
        row = conn.execute("SELECT version()").fetchone()
    version = str(row[0]) if row else "unknown version"
    match = re.search(r"SereneDB [0-9.]+", version)
    body = render_openstack(
        labels=labels,
        results=results,
        entries=entries,
        derive_s=seconds,
        schema=settings.slm_schema,
        version=match.group(0) if match else version,
        generated=datetime.now(UTC),
    )
    existing = output.read_text() if output.is_file() else TITLE
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(replace_section(existing, "openstack", body))
    return body


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="ground_truth.py", description=__doc__.splitlines()[0])
    parser.add_argument("dataset", choices=["openstack"], help="which ground truth to score")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="the Markdown results file")
    args = parser.parse_args(argv)
    try:
        body = run_openstack(args.output)
    except (GroundTruthError, ConfigError, psycopg.Error, OSError) as exc:
        print(f"ground_truth: {exc}", file=sys.stderr)
        return 2
    print(body)
    print(f"\nwritten to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
